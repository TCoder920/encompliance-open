/**
 * Description: Test suite for the Calendar component.
 * Purpose: Verifies that the Calendar component correctly implements paywall
 * restrictions based on user subscription tier and properly renders the calendar
 * interface for Pro and Enterprise users while showing upgrade prompts for Free users.
 * Tests modal functionality and AI scheduling features.
 */

import React from 'react';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import Calendar from '../Calendar';
import * as AuthContext from '../../../../contexts/AuthContext';
import { Tier, getTierFromSubscriptionStatus } from '../../../../utils/tiers';
import { canAccessFeature } from '../../../../utils/accessControl';
import axios from 'axios';

// Mock the axios module
jest.mock('axios');
const mockedAxios = axios as jest.Mocked<typeof axios>;

// Mock the AuthContext
jest.mock('../../../../contexts/AuthContext', () => ({
  useAuth: jest.fn(),
}));

// Mock FullCalendar as it's difficult to test with jsdom
jest.mock('@fullcalendar/react', () => {
  return {
    __esModule: true,
    default: jest.fn().mockImplementation(({ events, dateClick, eventClick }) => {
      return (
        <div data-testid="fullcalendar-mock">
          <button data-testid="date-click" onClick={() => dateClick({ dateStr: '2023-01-01', allDay: true })}>
            Date Click
          </button>
          <button 
            data-testid="event-click" 
            onClick={() => eventClick({ 
              event: { 
                id: '1', 
                title: 'Test Event', 
                startStr: '2023-01-01', 
                endStr: '2023-01-02',
                allDay: false,
                extendedProps: {
                  description: 'Test Description',
                  location: 'Test Location'
                }
              } 
            })}
          >
            Event Click
          </button>
          <div data-testid="events-count">{events.length}</div>
        </div>
      );
    }),
  };
});

describe('Calendar Component', () => {
  beforeEach(() => {
    jest.clearAllMocks();
    
    // Default mocked axios response for events
    mockedAxios.get.mockResolvedValue({
      data: [
        { 
          id: '1', 
          title: 'Test Event', 
          start: '2023-01-01', 
          end: '2023-01-02',
          description: 'Test Description',
          location: 'Test Location'
        }
      ]
    });
    
    // Default mocked AI scheduling response
    mockedAxios.post.mockResolvedValue({
      data: {
        event: {
          title: 'AI Generated Event',
          start: '2023-01-01T10:00:00',
          end: '2023-01-01T11:00:00',
          description: 'Generated by AI',
          location: 'Conference Room'
        }
      }
    });
  });

  test('shows upgrade prompt for FREE tier users', () => {
    // Mock user with FREE tier
    (AuthContext.useAuth as jest.Mock).mockReturnValue({
      user: { subscription_status: 'free' }
    });

    render(<Calendar />);
    
    // Should show the upgrade prompt
    expect(screen.getByText('Calendar Feature')).toBeInTheDocument();
    expect(screen.getByText(/available for Pro and Enterprise subscribers/i)).toBeInTheDocument();
    expect(screen.getByText('Upgrade Now')).toBeInTheDocument();
    
    // FullCalendar should not be rendered
    expect(screen.queryByTestId('fullcalendar-mock')).not.toBeInTheDocument();
  });

  test('shows calendar for PRO tier users', async () => {
    // Mock user with PRO tier
    (AuthContext.useAuth as jest.Mock).mockReturnValue({
      user: { subscription_status: 'pro' }
    });

    render(<Calendar />);
    
    // Should not show the upgrade prompt
    expect(screen.queryByText(/available for Pro and Enterprise subscribers/i)).not.toBeInTheDocument();
    
    // Wait for the calendar to load
    await waitFor(() => {
      expect(screen.getByTestId('fullcalendar-mock')).toBeInTheDocument();
    });
    
    // Should show AI scheduling button for PRO users
    expect(screen.getByText('AI Scheduling')).toBeInTheDocument();
  });

  test('shows calendar for ENTERPRISE tier users', async () => {
    // Mock user with ENTERPRISE tier
    (AuthContext.useAuth as jest.Mock).mockReturnValue({
      user: { subscription_status: 'enterprise' }
    });

    render(<Calendar />);
    
    // Wait for the calendar to load
    await waitFor(() => {
      expect(screen.getByTestId('fullcalendar-mock')).toBeInTheDocument();
    });
    
    // Should show AI scheduling button for ENTERPRISE users
    expect(screen.getByText('AI Scheduling')).toBeInTheDocument();
  });

  test('opens event modal on date click for PRO tier users', async () => {
    // Mock user with PRO tier
    (AuthContext.useAuth as jest.Mock).mockReturnValue({
      user: { subscription_status: 'pro' }
    });

    render(<Calendar />);
    
    // Wait for the calendar to load
    await waitFor(() => {
      expect(screen.getByTestId('fullcalendar-mock')).toBeInTheDocument();
    });
    
    // Click on a date
    fireEvent.click(screen.getByTestId('date-click'));
    
    // Modal should be visible
    expect(screen.getByText('New Event')).toBeInTheDocument();
  });

  test('opens event modal on event click for PRO tier users', async () => {
    // Mock user with PRO tier
    (AuthContext.useAuth as jest.Mock).mockReturnValue({
      user: { subscription_status: 'pro' }
    });

    render(<Calendar />);
    
    // Wait for the calendar to load
    await waitFor(() => {
      expect(screen.getByTestId('fullcalendar-mock')).toBeInTheDocument();
    });
    
    // Click on an event
    fireEvent.click(screen.getByTestId('event-click'));
    
    // Modal should be visible with event details
    expect(screen.getByText('Edit Event')).toBeInTheDocument();
    expect(screen.getByDisplayValue('Test Event')).toBeInTheDocument();
  });

  test('opens AI scheduling modal and processes request for PRO tier users', async () => {
    // Mock user with PRO tier
    (AuthContext.useAuth as jest.Mock).mockReturnValue({
      user: { subscription_status: 'pro' }
    });

    render(<Calendar />);
    
    // Wait for the calendar to load
    await waitFor(() => {
      expect(screen.getByTestId('fullcalendar-mock')).toBeInTheDocument();
    });
    
    // Click on AI Scheduling button
    fireEvent.click(screen.getByText('AI Scheduling'));
    
    // AI modal should be visible
    expect(screen.getByText('AI Scheduling Assistant')).toBeInTheDocument();
    
    // Enter AI prompt
    const promptInput = screen.getByPlaceholderText(/Schedule a compliance review/i);
    fireEvent.change(promptInput, { target: { value: 'Schedule a meeting tomorrow at 10am' } });
    
    // Click Create with AI button
    fireEvent.click(screen.getByText('Create with AI'));
    
    // Wait for the AI request to finish and switch to event modal
    await waitFor(() => {
      expect(screen.getByDisplayValue('AI Generated Event')).toBeInTheDocument();
    });
    
    // Verify axios was called with the correct parameters
    expect(mockedAxios.post).toHaveBeenCalledWith('/api/calendar/ai-schedule', {
      prompt: 'Schedule a meeting tomorrow at 10am'
    });
  });
}); 